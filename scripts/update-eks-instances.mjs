// Regenerates src/lib/eksInstances.ts for the EKS max pods calculator from
// AWS's own published data, so the calculator gives the numbers a real node
// gets. Zero dependencies (Node 22: fetch).
//
//   node scripts/update-eks-instances.mjs
//
// Sources:
// - awslabs/amazon-eks-ami nodeadm/internal/kubelet/instance-info.jsonl (MIT-0):
//   the table nodeadm embeds to set maxPods on EKS-optimized AL2023 nodes.
//   ENIs on the default network card, IPv4 addresses per ENI, vCPUs, memory.
// - aws/amazon-vpc-cni-k8s pkg/vpc/vpc_ip_resource_limit.go (Apache-2.0):
//   hypervisor and bare metal flags. The VPC CNI allows prefix delegation on
//   Nitro or bare metal instances (IsPrefixDelegationSupported in
//   pkg/awsutils/awsutils.go).
// - aws/amazon-vpc-cni-k8s misc/eni-max-pods.txt: AWS's generated default max
//   pods per instance type. The script refuses to write the file if the
//   formula disagrees with it for any instance type.
import { writeFileSync } from 'node:fs';

const EKS_AMI = 'https://raw.githubusercontent.com/awslabs/amazon-eks-ami/main/nodeadm/internal/kubelet/instance-info.jsonl';
const CNI_LIMITS = 'https://raw.githubusercontent.com/aws/amazon-vpc-cni-k8s/master/pkg/vpc/vpc_ip_resource_limit.go';
const CNI_MAX_PODS = 'https://raw.githubusercontent.com/aws/amazon-vpc-cni-k8s/master/misc/eni-max-pods.txt';
const OUT = new URL('../src/lib/eksInstances.ts', import.meta.url);

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
};

const latestCommit = async (repo, path) => {
  const res = await fetch(`https://api.github.com/repos/${repo}/commits?path=${path}&per_page=1`);
  const [c] = await res.json();
  return { sha: c.sha.slice(0, 12), date: c.commit.committer.date.slice(0, 10) };
};

const [infoText, limitsText, maxPodsText] = await Promise.all([get(EKS_AMI), get(CNI_LIMITS), get(CNI_MAX_PODS)]);
const [amiCommit, cniCommit] = await Promise.all([
  latestCommit('awslabs/amazon-eks-ami', 'nodeadm/internal/kubelet/instance-info.jsonl'),
  latestCommit('aws/amazon-vpc-cni-k8s', 'pkg/vpc/vpc_ip_resource_limit.go'),
]);

const info = infoText.split('\n').filter(Boolean).map((l) => JSON.parse(l));

const flags = new Map();
for (const m of limitsText.matchAll(/"([a-z0-9][a-z0-9.\-]+)":\s*\{([\s\S]*?)\n\t\},/g)) {
  const body = m[2];
  flags.set(m[1], {
    nitro: /HypervisorType:\s*"nitro"/.test(body),
    metal: /IsBareMetal:\s*true/.test(body),
  });
}

const awsMaxPods = new Map(
  maxPodsText.split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.trim().split(/\s+/)).map(([t, n]) => [t, Number(n)]),
);

const rows = [];
const problems = [];
// The managed node group cap depends on vCPUs. A few unusual or retired types
// (cr1.8xlarge, hs1.8xlarge, some .metal) have vcpus 0 in instance-info.jsonl;
// leave them out rather than guess, and the calculator's manual entry covers them.
const skipped = info.filter((i) => !(i.vcpus > 0)).map((i) => i.instanceType);
for (const i of info.filter((x) => x.vcpus > 0).sort((a, b) => a.instanceType.localeCompare(b.instanceType))) {
  const f = flags.get(i.instanceType);
  if (!f) problems.push(`${i.instanceType}: missing from vpc_ip_resource_limit.go`);
  const standard = i.defaultMaxENIs * (i.ipv4AddressesPerInterface - 1) + 2;
  const aws = awsMaxPods.get(i.instanceType);
  if (aws !== undefined && aws !== standard) problems.push(`${i.instanceType}: formula ${standard}, eni-max-pods.txt ${aws}`);
  rows.push([i.instanceType, i.defaultMaxENIs, i.ipv4AddressesPerInterface, i.vcpus, i.physicalMemoryMib, f && (f.nitro || f.metal) ? 1 : 0]);
}
if (problems.length) {
  console.error(`Not writing ${OUT.pathname}:\n  ${problems.slice(0, 20).join('\n  ')}`);
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const body = `// Generated by scripts/update-eks-instances.mjs on ${today}. Do not edit by hand.
//
// Sources:
//   awslabs/amazon-eks-ami nodeadm/internal/kubelet/instance-info.jsonl @ ${amiCommit.sha} (${amiCommit.date}), MIT-0
//   aws/amazon-vpc-cni-k8s pkg/vpc/vpc_ip_resource_limit.go @ ${cniCommit.sha} (${cniCommit.date}), Apache-2.0
// Checked: the default formula reproduces aws/amazon-vpc-cni-k8s misc/eni-max-pods.txt for every type.
// Left out because AWS's data has no vCPU count for them: ${skipped.join(', ') || 'none'}.
//
// [instance type, ENIs on the default network card, IPv4 addresses per ENI, vCPUs, memory MiB,
//  prefix delegation possible (Nitro or bare metal)]

export const EKS_DATA_SOURCE = {
  generated: '${today}',
  eksAmiCommit: '${amiCommit.sha}',
  vpcCniCommit: '${cniCommit.sha}',
  instanceTypes: ${rows.length},
} as const;

export const EKS_INSTANCES: readonly (readonly [string, number, number, number, number, 0 | 1])[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
writeFileSync(OUT, body);
console.log(`Skipped (no vCPU count): ${skipped.join(', ') || 'none'}`);
console.log(`Wrote ${rows.length} instance types to ${OUT.pathname} (eks-ami ${amiCommit.sha}, vpc-cni ${cniCommit.sha}).`);
